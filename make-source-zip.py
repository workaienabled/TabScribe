#!/usr/bin/env python3
"""Build source-code.zip: the full TabScribe source tree.

Everything extracts under a single top-level `tabscribe/` directory so the archive
does not scatter loose files into the current directory.

Included: the extension source, the probe/test suite and its audio fixtures, the
documentation, and the recorded probe findings (they are the evidence behind
several design decisions, and they are small).

Excluded, because all of it is derived and regenerable:
    __pycache__/             Python bytecode
    tabscribe-extension.zip  the packaged build output
    probe/shots/             screenshots, regenerated by shoot_model_notice.py
    source-code.zip          this script's own output
    .git/                    version control internals

Uses Python's zipfile rather than the zip(1) binary, which is not installed here.

Run:
    python3 make-source-zip.py
"""
import os
import sys
import zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.basename(ROOT)
OUT = os.path.join(ROOT, "source-code.zip")

EXCLUDE_DIRS = {".git", "__pycache__", "shots"}
EXCLUDE_FILES = {"source-code.zip", "tabscribe-extension.zip"}


def collect():
    """Yield (absolute path, archive name) for every file to include, sorted."""
    entries = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = sorted(d for d in dirnames if d not in EXCLUDE_DIRS)
        for fn in sorted(filenames):
            if fn in EXCLUDE_FILES:
                continue
            abs_path = os.path.join(dirpath, fn)
            rel = os.path.relpath(abs_path, ROOT)
            entries.append((abs_path, os.path.join(TOP, rel)))
    return entries


def main():
    entries = collect()
    if os.path.exists(OUT):
        os.remove(OUT)

    with zipfile.ZipFile(OUT, "w", zipfile.ZIP_DEFLATED) as z:
        for abs_path, arcname in entries:
            z.write(abs_path, arcname)

    size = os.path.getsize(OUT)
    print(f"wrote source-code.zip ({size / 1e6:.2f} MB, {len(entries)} files)\n")

    # Group the listing by directory so the contents are reviewable at a glance.
    by_dir = {}
    for _, arcname in entries:
        by_dir.setdefault(os.path.dirname(arcname), []).append(os.path.basename(arcname))
    for d in sorted(by_dir):
        print(f"  {d}/")
        for fn in sorted(by_dir[d]):
            print(f"      {fn}")

    # Verify the archive is readable and complete before reporting success.
    with zipfile.ZipFile(OUT) as z:
        bad = z.testzip()
        if bad is not None:
            print(f"\nARCHIVE CORRUPT at {bad}", file=sys.stderr)
            return 1
        if len(z.namelist()) != len(entries):
            print("\nENTRY COUNT MISMATCH", file=sys.stderr)
            return 1
    print("\nintegrity check: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
